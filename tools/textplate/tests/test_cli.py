# --- Interval parsing ---


class TestParseInterval:
    def test_seconds(self):
        assert parse_interval("5s") == 5.0

    def test_minutes(self):
        assert parse_interval("2m") == 120.0

    def test_hours(self):
        assert parse_interval("1h") == 3600.0

    def test_days(self):
        assert parse_interval("1d") == 86400.0

    def test_fractional(self):
        assert parse_interval("1.5h") == 5400.0

    def test_case_insensitive(self):
        assert parse_interval("5S") == 5.0
        assert parse_interval("2M") == 120.0

    def test_whitespace(self):
        assert parse_interval("  5s  ") == 5.0

    def test_space_between(self):
        assert parse_interval("5 s") == 5.0

    def test_invalid_unit(self):
        with pytest.raises(ValueError, match="Invalid interval"):
            parse_interval("5x")

    def test_no_unit(self):
        with pytest.raises(ValueError, match="Invalid interval"):
            parse_interval("5")

    def test_empty(self):
        with pytest.raises(ValueError, match="Invalid interval"):
            parse_interval("")

    def test_just_unit(self):
        with pytest.raises(ValueError, match="Invalid interval"):
            parse_interval("s")


class TestFormatInterval:
    def test_seconds(self):
        assert format_interval(5) == "5s"

    def test_fractional_seconds(self):
        assert format_interval(2.5) == "2.5s"

    def test_minutes(self):
        assert format_interval(120) == "2m"

    def test_hours(self):
        assert format_interval(3600) == "1h"

    def test_days(self):
        assert format_interval(86400) == "1d"


# --- Watch CLI ---


class TestWatchCLI:
    def test_watch_missing_file(self):
        result = runner.invoke(app, ["watch", "/nonexistent/file.md"])
        assert result.exit_code == 1

    def test_watch_bad_interval(self, tmp_path):
        tmpl = tmp_path / "x.textplate.md"
        tmpl.write_text("hello")
        result = runner.invoke(app, ["watch", str(tmpl), "--every", "5x"])
        assert result.exit_code == 1

    def test_watch_too_small_interval(self, tmp_path):
        tmpl = tmp_path / "x.textplate.md"
        tmpl.write_text("hello")
        result = runner.invoke(app, ["watch", str(tmpl), "--every", "0.1s"])
        assert result.exit_code == 1
