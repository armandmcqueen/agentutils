"""Tests for textplate CLI commands."""

from pathlib import Path

from typer.testing import CliRunner

from textplate.cli import app
from textplate.watch import format_interval, parse_interval

import pytest

FIXTURES = Path(__file__).parent / "fixtures"
runner = CliRunner()


# --- CLI press ---


class TestCLI:
    def test_press_stdout(self):
        result = runner.invoke(app, ["press", str(FIXTURES / "simple.textplate.md"), "--stdout"])
        assert result.exit_code == 0
        assert "Hello, world!" in result.stdout
        assert "**intro** section" in result.stdout
        assert "Generated by textplate" in result.stdout

    def test_press_writes_file(self, tmp_path):
        # Copy fixtures to tmp_path so output goes there
        template = FIXTURES.joinpath("simple.textplate.md").read_text()
        tmpl_file = tmp_path / "doc.textplate.md"
        tmpl_file.write_text(template)

        # Copy referenced files
        (tmp_path / "greeting.txt").write_text(FIXTURES.joinpath("greeting.txt").read_text())
        (tmp_path / "snippets.md").write_text(FIXTURES.joinpath("snippets.md").read_text())

        result = runner.invoke(app, ["press", str(tmpl_file)])
        assert result.exit_code == 0

        out_file = tmp_path / "doc.md"
        assert out_file.exists()
        content = out_file.read_text()
        assert "Hello, world!" in content
        assert "Generated by textplate" in content

    def test_press_missing_file(self):
        result = runner.invoke(app, ["press", "/nonexistent/file.md"])
        assert result.exit_code == 1

    def test_press_unresolvable_reference(self, tmp_path):
        tmpl = tmp_path / "bad.textplate.md"
        tmpl.write_text("[](text::./nope.md)")
        result = runner.invoke(app, ["press", str(tmpl)])
        assert result.exit_code == 1
        assert "Error" in result.stdout or "Error" in (result.stderr or "")


